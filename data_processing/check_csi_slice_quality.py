@dataclass(frozen=True)
class VideoReviewRule:
    session_id: str
    clip_expr: str
    category: str
    description: str
    resample_status: str
    match_kind: str
    exact_ids: frozenset[str] = frozenset()
    prefix: str = ""
    start_trial: int | None = None
    end_trial: int | None = None

    def matches(self, sample_id: str) -> bool:
        if self.match_kind == "exact":
            return sample_id in self.exact_ids
        if self.match_kind == "wildcard":
            return sample_id.startswith(self.prefix)
        if self.match_kind == "from_trial":
            return self._trial_matches(sample_id, upper_bound=None)
        if self.match_kind == "range":
            return sample_id in self.exact_ids or self._trial_matches(sample_id, upper_bound=self.end_trial)
        return False

    def _trial_matches(self, sample_id: str, upper_bound: int | None) -> bool:
        if self.start_trial is None or not self.prefix:
            return False
        if not sample_id.startswith(self.prefix):
            return False
        suffix = sample_id[len(self.prefix) :]
        if not re.fullmatch(r"\d{3}", suffix):
            return False
        trial = int(suffix)
        if trial < self.start_trial:
            return False
        if upper_bound is not None and trial > upper_bound:
            return False
        return True


