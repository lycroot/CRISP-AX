def numeric_values(rows: list[dict[str, object]], field: str) -> list[float]:
    values = []
    for row in rows:
        value = to_float(row.get(field))
        if value is not None:
            values.append(value)
    return values


def summarize_distribution(rows: list[dict[str, object]], field: str) -> str:
    values = sorted(numeric_values(rows, field))
    if not values:
        return "count=0"
    return (
        f"count={len(values)}, min={values[0]:.3f}, "
        f"p50={percentile(values, 0.50):.3f}, p95={percentile(values, 0.95):.3f}, max={values[-1]:.3f}"
    )


def summarize_numeric_values(values: list[float], target_rate_hz: float | None = None) -> dict[str, float | int]:
    values = sorted(values)
    if not values:
        summary: dict[str, float | int] = {
            "count": 0,
            "min": math.nan,
            "p50": math.nan,
            "p95": math.nan,
            "max": math.nan,
            "mean": math.nan,
            "std": math.nan,
        }
    else:
        mean = sum(values) / len(values)
        variance = sum((value - mean) ** 2 for value in values) / len(values)
        summary = {
            "count": len(values),
            "min": values[0],
            "p50": percentile(values, 0.50),
            "p95": percentile(values, 0.95),
            "max": values[-1],
            "mean": mean,
            "std": math.sqrt(variance),
        }
    if target_rate_hz is not None and math.isfinite(float(summary["mean"])):
        delta = float(summary["mean"]) - target_rate_hz
        summary["mean_delta_from_target"] = delta
        summary["mean_delta_percent_from_target"] = (delta / target_rate_hz * 100.0) if target_rate_hz else math.nan
    else:
        summary["mean_delta_from_target"] = math.nan
        summary["mean_delta_percent_from_target"] = math.nan
    return summary


def has_flag(row: dict[str, object], flag_name: str) -> bool:
    flags = str(row.get("quality_flags", ""))
    return flag_name in {flag for flag in flags.split(";") if flag}


def summarize_packet_rates(rows: list[dict[str, object]], target_rate_hz: float = 100.0) -> dict[str, object]:
    all_rates: list[float] = []
    normal_rates: list[float] = []
    outlier_ids: list[str] = []

    for row in rows:
        rate = to_float(row.get("packet_rate_hz"))
        if rate is None:
            continue
        all_rates.append(rate)
        is_rate_outlier = has_flag(row, "low_packet_rate") or has_flag(row, "high_packet_rate")
        if is_rate_outlier:
            outlier_ids.append(str(row.get("sample_id", "")))
        else:
            normal_rates.append(rate)

    all_summary = summarize_numeric_values(all_rates, target_rate_hz)
    normal_summary = summarize_numeric_values(normal_rates, target_rate_hz)
    return {
        "all_count": all_summary["count"],
        "all_mean": all_summary["mean"],
        "all_std": all_summary["std"],
        "all_min": all_summary["min"],
        "all_p50": all_summary["p50"],
        "all_p95": all_summary["p95"],
        "all_max": all_summary["max"],
        "all_mean_delta_from_target": all_summary["mean_delta_from_target"],
        "all_mean_delta_percent_from_target": all_summary["mean_delta_percent_from_target"],
        "normal_count": normal_summary["count"],
        "normal_mean": normal_summary["mean"],
        "normal_std": normal_summary["std"],
        "normal_min": normal_summary["min"],
        "normal_p50": normal_summary["p50"],
        "normal_p95": normal_summary["p95"],
        "normal_max": normal_summary["max"],
        "normal_mean_delta_from_target": normal_summary["mean_delta_from_target"],
        "normal_mean_delta_percent_from_target": normal_summary["mean_delta_percent_from_target"],
        "rate_outlier_count": len(outlier_ids),
        "rate_outlier_sample_ids": outlier_ids,
    }


def format_rate_summary(summary: dict[str, object], prefix: str) -> str:
    count = int(summary[f"{prefix}_count"])
    if count == 0:
        return "count=0"
    return (
        f"count={count}, mean={float(summary[f'{prefix}_mean']):.3f} Hz, "
        f"std={float(summary[f'{prefix}_std']):.3f}, min={float(summary[f'{prefix}_min']):.3f}, "
        f"p50={float(summary[f'{prefix}_p50']):.3f}, p95={float(summary[f'{prefix}_p95']):.3f}, "
        f"max={float(summary[f'{prefix}_max']):.3f}, "
        f"mean_delta_from_target={float(summary[f'{prefix}_mean_delta_from_target']):+.3f} Hz "
        f"({float(summary[f'{prefix}_mean_delta_percent_from_target']):+.3f}%)"
    )


def percentile(values: list[float], q: float) -> float:
    if not values:
        return math.nan
    if len(values) == 1:
        return values[0]
    pos = (len(values) - 1) * q
    lower = math.floor(pos)
    upper = math.ceil(pos)
    if lower == upper:
        return values[int(pos)]
    weight = pos - lower
    return values[lower] * (1 - weight) + values[upper] * weight


def flag_counts(rows: list[dict[str, object]]) -> Counter[str]:
    counts: Counter[str] = Counter()
    for row in rows:
        flags = str(row.get("quality_flags", ""))
        if flags == "ok":
            counts["ok"] += 1
            continue
        for flag in flags.split(";"):
            if flag:
                counts[flag] += 1
    return counts


