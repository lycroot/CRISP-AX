def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def write_csv(path: Path, rows: list[dict[str, object]], fields: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field, "") for field in fields})


def to_int(value: object) -> int | None:
    try:
        if value is None or value == "":
            return None
        return int(float(str(value)))
    except ValueError:
        return None


def to_float(value: object) -> float | None:
    try:
        if value is None or value == "":
            return None
        number = float(str(value))
    except ValueError:
        return None
    return number if math.isfinite(number) else None


def fmt_float(value: float | int | None, digits: int = 6) -> str:
    if value is None:
        return ""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return ""
    if not math.isfinite(number):
        return ""
    return f"{number:.{digits}f}"


def rel(path: Path | None, root: Path) -> str:
    if path is None:
        return ""
    try:
        return str(path.resolve().relative_to(root.resolve()))
    except ValueError:
        return str(path)


def resolve_path(root: Path, value: str) -> Path:
    path = Path(value)
    if not path.is_absolute():
        path = root / path
    return path


def clean_markdown_cell(value: str) -> str:
    value = value.strip()
    value = value.replace("**", "")
    return value.strip()


def extract_code_cell(value: str) -> str:
    match = re.search(r"`([^`]+)`", value)
    if match:
        return match.group(1).strip()
    return clean_markdown_cell(value)


def make_video_review_rule(
    session_id: str,
    clip_expr: str,
    category: str,
    description: str,
    resample_status: str,
) -> VideoReviewRule:
    expr = clip_expr.replace("–", "-").replace("—", "-").strip()
    expr = re.sub(r"\s+", " ", expr)

    if "*" in expr:
        return VideoReviewRule(
            session_id=session_id,
            clip_expr=clip_expr,
            category=category,
            description=description,
            resample_status=resample_status,
            match_kind="wildcard",
            prefix=expr.split("*", 1)[0],
        )

    from_match = re.fullmatch(r"(.+_R)(\d{3})\s*之后", expr)
    if from_match:
        return VideoReviewRule(
            session_id=session_id,
            clip_expr=clip_expr,
            category=category,
            description=description,
            resample_status=resample_status,
            match_kind="from_trial",
            prefix=from_match.group(1),
            start_trial=int(from_match.group(2)),
        )

    range_match = re.fullmatch(r"(.+_R)(\d{3})-(\d{3})", expr)
    if range_match:
        prefix = range_match.group(1)
        start_trial = int(range_match.group(2))
        end_trial = int(range_match.group(3))
        exact_ids = frozenset(f"{prefix}{trial:03d}" for trial in range(start_trial, end_trial + 1))
        return VideoReviewRule(
            session_id=session_id,
            clip_expr=clip_expr,
            category=category,
            description=description,
            resample_status=resample_status,
            match_kind="range",
            exact_ids=exact_ids,
            prefix=prefix,
            start_trial=start_trial,
            end_trial=end_trial,
        )

    return VideoReviewRule(
        session_id=session_id,
        clip_expr=clip_expr,
        category=category,
        description=description,
        resample_status=resample_status,
        match_kind="exact",
        exact_ids=frozenset({expr}),
    )


def parse_video_review_rules(markdown_text: str) -> list[VideoReviewRule]:
    rules: list[VideoReviewRule] = []
    in_detail_table = False
    saw_detail_heading = False

    for raw_line in markdown_text.splitlines():
        line = raw_line.strip()
        if line.startswith("## 详细问题清单"):
            in_detail_table = True
            saw_detail_heading = True
            continue
        if in_detail_table and line.startswith("## "):
            break
        if saw_detail_heading and not in_detail_table:
            continue
        if not line.startswith("|") or "`" not in line:
            continue

        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if len(cells) < 6 or cells[0].strip() in {"#", ":-:"}:
            continue

        session_id = clean_markdown_cell(cells[1])
        clip_expr = extract_code_cell(cells[2])
        category = clean_markdown_cell(cells[3])
        description = clean_markdown_cell(cells[4])
        resample_status = clean_markdown_cell(cells[5])
        if not session_id or not clip_expr:
            continue
        rules.append(make_video_review_rule(session_id, clip_expr, category, description, resample_status))

    return rules


def parse_csi_payload(payload: bytes, num_rx: int, num_tx: int, num_subcarriers: int) -> np.ndarray:
    expected_values = 2 * num_rx * num_tx * num_subcarriers
    raw = np.frombuffer(payload, dtype="<i2")
    if raw.size != expected_values:
        raise ValueError(f"payload value count mismatch: got={raw.size}, expected={expected_values}")
    raw = raw.reshape(num_rx, num_tx, num_subcarriers, 2)
    real = raw[..., 0].astype(np.float32)
    imag = raw[..., 1].astype(np.float32)
    csi = real + 1j * imag
    return np.transpose(csi, (2, 0, 1))


def read_dat_quality(path: Path, payload_sample_packets: int = 32) -> DatQuality:
    file_size = path.stat().st_size
    if file_size == 0:
        return DatQuality(parse_status="empty", file_size_bytes=0, notes="empty file")

    packet_count = 0
    bad_packet_count = 0
    trailing_partial_packet_count = 0
    csi_size_mismatch_count = 0
    bad_csi_size_count = 0
    payload_packets_checked = 0
    zero_packet_count = 0
    stopped_on_partial = False
    notes: list[str] = []

    rx_values: Counter[int] = Counter()
    tx_values: Counter[int] = Counter()
    subcarrier_values: Counter[int] = Counter()

    total_values = 0
    nonzero_values = 0
    amp_sum = 0.0
    amp_sq_sum = 0.0
    amp_min: float | None = None
    amp_max: float | None = None
    link_total: defaultdict[tuple[int, int], int] = defaultdict(int)
    link_nonzero: defaultdict[tuple[int, int], int] = defaultdict(int)
    link_amp_sum: defaultdict[tuple[int, int], float] = defaultdict(float)

    with path.open("rb") as f:
        offset = 0
        while offset + HEADER_SIZE <= file_size:
            f.seek(offset)
            header = f.read(HEADER_SIZE)
            if len(header) < HEADER_SIZE:
                trailing_partial_packet_count += 1
                bad_packet_count += 1
                stopped_on_partial = True
                break

            csi_size = struct.unpack_from("<I", header, 0)[0]
            num_rx = header[46]
            num_tx = header[47]
            num_subcarriers = struct.unpack_from("<I", header, 52)[0]
            rx_values[num_rx] += 1
            tx_values[num_tx] += 1
            subcarrier_values[num_subcarriers] += 1

            if csi_size <= 0:
                bad_csi_size_count += 1
                bad_packet_count += 1
                notes.append(f"bad csi_size at offset {offset}")
                break

            next_offset = offset + HEADER_SIZE + csi_size
            if next_offset > file_size:
                trailing_partial_packet_count += 1
                bad_packet_count += 1
                stopped_on_partial = True
                break

            expected_size = 4 * num_rx * num_tx * num_subcarriers
            if csi_size != expected_size:
                csi_size_mismatch_count += 1
                bad_packet_count += 1
            else:
                packet_count += 1
                if payload_packets_checked < payload_sample_packets:
                    payload = f.read(csi_size)
                    try:
                        csi = parse_csi_payload(payload, num_rx, num_tx, num_subcarriers)
                    except ValueError as exc:
                        bad_packet_count += 1
                        notes.append(str(exc))
                    else:
                        payload_packets_checked += 1
                        amp = np.abs(csi)
                        packet_nonzero = int(np.count_nonzero(csi))
                        packet_total = int(csi.size)
                        if packet_nonzero == 0:
                            zero_packet_count += 1

                        total_values += packet_total
                        nonzero_values += packet_nonzero
                        amp_sum += float(np.sum(amp))
                        amp_sq_sum += float(np.sum(amp**2))
                        cur_min = float(np.min(amp))
                        cur_max = float(np.max(amp))
                        amp_min = cur_min if amp_min is None else min(amp_min, cur_min)
                        amp_max = cur_max if amp_max is None else max(amp_max, cur_max)

                        for rx in range(num_rx):
                            for tx in range(num_tx):
                                link = (rx, tx)
                                values = csi[:, rx, tx]
                                link_total[link] += int(values.size)
                                link_nonzero[link] += int(np.count_nonzero(values))
                                link_amp_sum[link] += float(np.sum(np.abs(values)))

            offset = next_offset

        if offset < file_size and not stopped_on_partial:
            trailing_partial_packet_count += 1
            bad_packet_count += 1

    if packet_count == 0:
        parse_status = "empty" if file_size == 0 else "error"
    elif bad_packet_count:
        parse_status = "warn"
    else:
        parse_status = "ok"

    if total_values:
        global_nonzero_ratio = nonzero_values / total_values
        global_amp_mean = amp_sum / total_values
        global_amp_var = amp_sq_sum / total_values - global_amp_mean**2
        global_amp_std = math.sqrt(max(global_amp_var, 0.0))
    else:
        global_nonzero_ratio = math.nan
        global_amp_mean = math.nan
        global_amp_std = math.nan

    link_ratios = []
    link_amp_means = []
    for link, total in link_total.items():
        if total <= 0:
            continue
        link_ratios.append(link_nonzero[link] / total)
        link_amp_means.append(link_amp_sum[link] / total)
    dead_link_count = sum(1 for ratio in link_ratios if ratio == 0.0)

    return DatQuality(
        parse_status=parse_status,
        packet_count=packet_count,
        file_size_bytes=file_size,
        bad_packet_count=bad_packet_count,
        trailing_partial_packet_count=trailing_partial_packet_count,
        csi_size_mismatch_count=csi_size_mismatch_count,
        bad_csi_size_count=bad_csi_size_count,
        payload_packets_checked=payload_packets_checked,
        zero_packet_count=zero_packet_count,
        num_rx_values=";".join(str(value) for value in sorted(rx_values)),
        num_tx_values=";".join(str(value) for value in sorted(tx_values)),
        num_subcarrier_values=";".join(str(value) for value in sorted(subcarrier_values)),
        global_nonzero_ratio=global_nonzero_ratio,
        global_amp_min=amp_min if amp_min is not None else math.nan,
        global_amp_mean=global_amp_mean,
        global_amp_std=global_amp_std,
        global_amp_max=amp_max if amp_max is not None else math.nan,
        dead_link_count=dead_link_count,
        link_nonzero_ratio_min=min(link_ratios) if link_ratios else math.nan,
        link_amp_mean_min=min(link_amp_means) if link_amp_means else math.nan,
        notes="; ".join(notes),
    )


def classify_packet_rate(
    packet_count: int | None,
    action_duration_sec: float | None,
    low_hz: float,
    high_hz: float,
) -> list[str]:
    if packet_count is None or action_duration_sec is None or action_duration_sec <= 0:
        return ["missing_packet_rate"]
    rate = packet_count / action_duration_sec
    if rate < low_hz:
        return ["low_packet_rate"]
    if rate > high_hz:
        return ["high_packet_rate"]
    return []


def final_status_from_flags(flags: list[str]) -> str:
    if any(flag in EXCLUDE_FLAGS for flag in flags):
        return "exclude"
    if flags:
        return "warn"
    return "ok"


def select_rows(rows: list[dict[str, str]], args: argparse.Namespace) -> list[dict[str, str]]:
    sessions = set(args.session)
    actions = set(args.action)
    sample_ids = set(args.sample_id)
    selected = []
    for row in rows:
        if sessions and row.get("session_id") not in sessions:
            continue
        if actions and row.get("action_id") not in actions:
            continue
        if sample_ids and row.get("sample_id") not in sample_ids:
            continue
        selected.append(row)
    if args.limit is not None:
        selected = selected[: args.limit]
    return selected


def matching_review_rules(sample_id: str, rules: list[VideoReviewRule]) -> list[VideoReviewRule]:
    return [rule for rule in rules if rule.matches(sample_id)]


def build_quality_row(
    root: Path,
    slice_row: dict[str, str],
    sync_row: dict[str, str] | None,
    review_rules: list[VideoReviewRule],
    args: argparse.Namespace,
) -> dict[str, object]:
    sample_id = slice_row.get("sample_id", "")
    csi_out_value = slice_row.get("csi_out_path", "")
    csi_path = resolve_path(root, csi_out_value) if csi_out_value else root / "__missing_csi_out_path__"
    flags: list[str] = []
    notes: list[str] = []

    expected_slice = to_int(slice_row.get("csi_packets_expected"))
    written_slice = to_int(slice_row.get("csi_packets_written"))
    expected_sync = to_int(sync_row.get("csi_action_packet_count")) if sync_row else None
    action_duration_sec = to_float(sync_row.get("action_duration_sec")) if sync_row else None
    packet_rate_hz: float | None = None

    if sync_row is None:
        flags.append("missing_sync_index_row")
    elif sync_row.get("sync_status") and sync_row.get("sync_status") != "ok":
        flags.append("sync_status_not_ok")
    if slice_row.get("status") and slice_row.get("status") != "ok":
        flags.append("slice_status_not_ok")
    if slice_row.get("sync_quality_flags") and slice_row.get("sync_quality_flags") != "ok":
        flags.append("sync_quality_warning")

    if not csi_out_value or not csi_path.exists():
        quality = DatQuality(parse_status="missing", notes="missing csi slice file")
        flags.append("missing_csi_slice_file")
    elif csi_path.stat().st_size == 0:
        quality = DatQuality(parse_status="empty", file_size_bytes=0, notes="empty csi slice file")
        flags.append("empty_csi_slice_file")
    else:
        quality = read_dat_quality(csi_path, payload_sample_packets=args.payload_sample_packets)
        if quality.packet_count == 0:
            flags.append("no_dat_packets")
        if quality.trailing_partial_packet_count:
            flags.append("trailing_partial_packet")
        if quality.csi_size_mismatch_count:
            flags.append("csi_size_mismatch")
        if quality.bad_csi_size_count:
            flags.append("bad_csi_size")

    dat_packet_count = quality.packet_count if quality.packet_count else None
    if dat_packet_count is not None and action_duration_sec:
        packet_rate_hz = dat_packet_count / action_duration_sec
        flags.extend(classify_packet_rate(dat_packet_count, action_duration_sec, args.packet_rate_low_hz, args.packet_rate_high_hz))
    elif dat_packet_count is None:
        flags.append("missing_packet_rate")

    if dat_packet_count is not None and written_slice is not None and dat_packet_count != written_slice:
        flags.append("packet_count_mismatch_slice_index")
    if dat_packet_count is not None and expected_slice is not None and dat_packet_count != expected_slice:
        flags.append("packet_count_mismatch_slice_expected")
    if dat_packet_count is not None and expected_sync is not None and dat_packet_count != expected_sync:
        flags.append("packet_count_mismatch_sync_index")

    if quality.payload_packets_checked:
        if quality.global_nonzero_ratio == 0.0:
            flags.append("all_zero_csi_payload")
        elif math.isfinite(quality.global_nonzero_ratio) and quality.global_nonzero_ratio < args.low_nonzero_ratio:
            flags.append("low_nonzero_ratio")
        if quality.zero_packet_count:
            flags.append("sampled_zero_packet")
        if quality.dead_link_count:
            flags.append("dead_rx_tx_link")
        if math.isfinite(quality.global_amp_std) and quality.global_amp_std <= args.constant_amp_std:
            flags.append("constant_csi_amplitude")
    else:
        flags.append("payload_not_checked")

    matched_reviews = matching_review_rules(sample_id, review_rules)
    if matched_reviews:
        flags.append("video_review_issue")
        if any("✅" in rule.resample_status or "已补采" in rule.resample_status or "有补采" in rule.resample_status for rule in matched_reviews):
            flags.append("video_review_resampled_available")
        if any("❌" in rule.resample_status or "未补采" in rule.resample_status or "未修正" in rule.resample_status for rule in matched_reviews):
            flags.append("video_review_unresolved")

    if quality.notes:
        notes.append(quality.notes)
    if sync_row and sync_row.get("notes"):
        notes.append(f"sync: {sync_row['notes']}")
    if slice_row.get("notes"):
        notes.append(f"slice: {slice_row['notes']}")

    flags = sorted(set(flags))
