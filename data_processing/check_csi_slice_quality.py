def progress(enabled: bool, message: str) -> None:
    if not enabled:
        return
    width = 120
    sys.stderr.write("\r" + message[:width].ljust(width))
    sys.stderr.flush()


def progress_done(enabled: bool) -> None:
    if enabled:
        sys.stderr.write("\n")
        sys.stderr.flush()


def format_bar(done: int, total: int) -> str:
    width = 28
    ratio = done / total if total else 1.0
    filled = int(round(width * ratio))
    return "[" + "#" * filled + "-" * (width - filled) + f"] {ratio * 100:5.1f}%"


def main() -> None:
    args = parse_args()
    root = Path(args.project_root).resolve()
    slice_index = resolve_path(root, args.slice_index)
    sync_index = resolve_path(root, args.sync_index)
    output_dir = resolve_path(root, args.output_dir)

    slice_rows = read_csv(slice_index)
    sync_rows = read_csv(sync_index)
    sync_by_sample_id = {row.get("sample_id", ""): row for row in sync_rows if row.get("sample_id")}

    review_rules: list[VideoReviewRule] = []
    if args.video_review:
        review_path = resolve_path(root, args.video_review)
        if review_path.exists():
            review_rules = parse_video_review_rules(review_path.read_text(encoding="utf-8"))

    selected = select_rows(slice_rows, args)
    quality_rows: list[dict[str, object]] = []
    for idx, slice_row in enumerate(selected, start=1):
        sample_id = slice_row.get("sample_id", "")
        progress(
            not args.quiet,
            f"{format_bar(idx, len(selected))} checking {idx}/{len(selected)} {sample_id}",
        )
        quality_rows.append(
            build_quality_row(root, slice_row, sync_by_sample_id.get(sample_id), review_rules, args)
        )
    progress_done(not args.quiet)

    quality_csv = output_dir / "csi_slice_quality.csv"
    outlier_csv = output_dir / "csi_outlier_samples.csv"
    report_md = output_dir / "csi_slice_quality_summary.md"
    outliers = [row for row in quality_rows if row.get("final_status") != "ok"]

    write_csv(quality_csv, quality_rows, OUT_FIELDS)
    write_csv(outlier_csv, outliers, OUTLIER_FIELDS)
    write_summary(
        report_md,
        root,
        args,
        slice_count=len(slice_rows),
        sync_count=len(sync_rows),
        review_rule_count=len(review_rules),
        rows=quality_rows,
        outlier_count=len(outliers),
    )

    status_counts = Counter(str(row.get("final_status", "")) for row in quality_rows)
    print(f"processed samples: {len(quality_rows)}")
    for status, count in sorted(status_counts.items()):
        print(f"{status}: {count}")
    print(f"quality csv: {rel(quality_csv, root)}")
    print(f"outlier csv: {rel(outlier_csv, root)}")
    print(f"report: {rel(report_md, root)}")


if __name__ == "__main__":
    main()
